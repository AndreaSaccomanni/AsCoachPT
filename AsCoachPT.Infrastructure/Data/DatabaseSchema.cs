using Microsoft.EntityFrameworkCore;

namespace AsCoachPT.Infrastructure.Data;

/// <summary>
/// Adeguamenti dello schema per i database già esistenti. Il progetto usa
/// EnsureCreated (che non altera le tabelle), quindi le nuove colonne vengono
/// aggiunte qui in modo idempotente all'avvio.
/// </summary>
public static class DatabaseSchema
{
    public static async Task AssicuraAsync(AsCoachDbContext contesto, CancellationToken tokenAnnullamento = default)
    {
        var provider = contesto.Database.ProviderName ?? string.Empty;

        if (provider.Contains("Npgsql", StringComparison.OrdinalIgnoreCase))
        {
            await contesto.Database.ExecuteSqlRawAsync(
                "ALTER TABLE indirizzi ADD COLUMN IF NOT EXISTS attivo boolean NOT NULL DEFAULT true;",
                tokenAnnullamento);
            await contesto.Database.ExecuteSqlRawAsync(
                "ALTER TABLE utenti ADD COLUMN IF NOT EXISTS telefono text NOT NULL DEFAULT '';",
                tokenAnnullamento);
            await contesto.Database.ExecuteSqlRawAsync(
                "ALTER TABLE utenti ADD COLUMN IF NOT EXISTS reset_token_hash text;",
                tokenAnnullamento);
            await contesto.Database.ExecuteSqlRawAsync(
                "ALTER TABLE utenti ADD COLUMN IF NOT EXISTS reset_token_scadenza timestamp with time zone;",
                tokenAnnullamento);
            await contesto.Database.ExecuteSqlRawAsync(
                "ALTER TABLE utenti ADD COLUMN IF NOT EXISTS versione_sicurezza integer NOT NULL DEFAULT 1;",
                tokenAnnullamento);
            await contesto.Database.ExecuteSqlRawAsync(
                "CREATE TABLE IF NOT EXISTS notifiche_prenotazioni (" +
                "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "prenotazione_id bigint NULL, " +
                "tipo text NOT NULL, " +
                "messaggio text NOT NULL, " +
                "creata_il timestamp with time zone NOT NULL, " +
                "letta boolean NOT NULL DEFAULT false);",
                tokenAnnullamento);
            return;
        }

        if (provider.Contains("Sqlite", StringComparison.OrdinalIgnoreCase))
        {
            var esisteAttivo = await contesto.Database
                .SqlQueryRaw<int>("SELECT COUNT(*) AS \"Value\" FROM pragma_table_info('indirizzi') WHERE name = 'attivo'")
                .FirstOrDefaultAsync(tokenAnnullamento);

            if (esisteAttivo == 0)
            {
                await contesto.Database.ExecuteSqlRawAsync(
                    "ALTER TABLE indirizzi ADD COLUMN attivo INTEGER NOT NULL DEFAULT 1;",
                    tokenAnnullamento);
            }

            var esisteTelefono = await contesto.Database
                .SqlQueryRaw<int>("SELECT COUNT(*) AS \"Value\" FROM pragma_table_info('utenti') WHERE name = 'telefono'")
                .FirstOrDefaultAsync(tokenAnnullamento);

            if (esisteTelefono == 0)
            {
                await contesto.Database.ExecuteSqlRawAsync(
                    "ALTER TABLE utenti ADD COLUMN telefono TEXT NOT NULL DEFAULT '';",
                    tokenAnnullamento);
            }

            var esisteResetToken = await contesto.Database
                .SqlQueryRaw<int>("SELECT COUNT(*) AS \"Value\" FROM pragma_table_info('utenti') WHERE name = 'reset_token_hash'")
                .FirstOrDefaultAsync(tokenAnnullamento);

            if (esisteResetToken == 0)
            {
                await contesto.Database.ExecuteSqlRawAsync(
                    "ALTER TABLE utenti ADD COLUMN reset_token_hash TEXT;",
                    tokenAnnullamento);
            }

            var esisteResetScadenza = await contesto.Database
                .SqlQueryRaw<int>("SELECT COUNT(*) AS \"Value\" FROM pragma_table_info('utenti') WHERE name = 'reset_token_scadenza'")
                .FirstOrDefaultAsync(tokenAnnullamento);

            if (esisteResetScadenza == 0)
            {
                await contesto.Database.ExecuteSqlRawAsync(
                    "ALTER TABLE utenti ADD COLUMN reset_token_scadenza TEXT;",
                    tokenAnnullamento);
            }

            var esisteVersione = await contesto.Database
                .SqlQueryRaw<int>("SELECT COUNT(*) AS \"Value\" FROM pragma_table_info('utenti') WHERE name = 'versione_sicurezza'")
                .FirstOrDefaultAsync(tokenAnnullamento);

            if (esisteVersione == 0)
            {
                await contesto.Database.ExecuteSqlRawAsync(
                    "ALTER TABLE utenti ADD COLUMN versione_sicurezza INTEGER NOT NULL DEFAULT 1;",
                    tokenAnnullamento);
            }

            await contesto.Database.ExecuteSqlRawAsync(
                "CREATE TABLE IF NOT EXISTS notifiche_prenotazioni (" +
                "id INTEGER PRIMARY KEY AUTOINCREMENT, " +
                "prenotazione_id INTEGER NULL, " +
                "tipo TEXT NOT NULL, " +
                "messaggio TEXT NOT NULL, " +
                "creata_il TEXT NOT NULL, " +
                "letta INTEGER NOT NULL DEFAULT 0);",
                tokenAnnullamento);
        }
    }
}
